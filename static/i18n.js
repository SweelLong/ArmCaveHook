function _(key) {
  const lang = new URLSearchParams(location.search).get("lang") ||
    (document.cookie.match(/lang=(\w+)/) || [])[1] || "zh";
  return (I18N[lang] || I18N.zh)[key] || (I18N.zh[key] || key);
}

// persist lang in cookie
(function () {
  const lang = new URLSearchParams(location.search).get("lang");
  if (lang) { document.cookie = "lang=" + lang + ";path=/;max-age=31536000"; }
})();
